function resolveLang(): string {
    const chosen = (Settings.plugins as any).BadgeFarmer?.language as string | undefined;
    if (chosen && chosen !== "auto") return chosen;

    const raw = document.documentElement.lang || navigator.language || "en";
    if (raw in dict) return raw;
    const base = raw.split("-")[0];
    if (base === "pt") return "pt-BR";
    return base in dict ? base : "en";
}

export function t(key: Key, vars?: Record<string, string | number>): string {
    let text = dict[resolveLang()]?.[key] ?? en[key];
    if (vars) text = text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
    return text;
}
